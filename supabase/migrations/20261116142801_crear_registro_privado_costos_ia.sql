create table if not exists public.velox_ai_usage (
    id bigint generated by default as identity primary key,
    restaurante_id uuid references public.restaurantes(id) on delete set null,
    operacion text not null,
    modelo text not null,
    input_tokens bigint not null default 0,
    output_tokens bigint not null default 0,
    total_tokens bigint not null default 0,
    costo_estimado_usd numeric(16,8),
    detalle_uso jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists velox_ai_usage_restaurant_created_idx
    on public.velox_ai_usage (restaurante_id, created_at desc);

alter table public.velox_ai_usage enable row level security;
revoke all on table public.velox_ai_usage from public, anon, authenticated;
grant select, insert on table public.velox_ai_usage to service_role;

